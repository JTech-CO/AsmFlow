{
    return (int)((llhttp_t *)storage)->lenient_flags;
}

/* The method enumerators, in the order include/http.inc lists them, so a test
 * can assert the two agree rather than trusting a comment (ADR 0007). */
void af_llhttp_method_ordinals(int *out7)
{
    out7[0] = HTTP_DELETE;
    out7[1] = HTTP_GET;
    out7[2] = HTTP_HEAD;
    out7[3] = HTTP_POST;
    out7[4] = HTTP_PUT;
    out7[5] = HTTP_CONNECT;
    out7[6] = HTTP_OPTIONS;
}

/* Likewise for the error codes assembly distinguishes: ok, paused,
 * paused-on-upgrade, and the code a callback's -1 produces. */
void af_llhttp_errno_ordinals(int *out4)
{
    out4[0] = HPE_OK;
    out4[1] = HPE_PAUSED;
    out4[2] = HPE_PAUSED_UPGRADE;
    out4[3] = HPE_USER;
}
